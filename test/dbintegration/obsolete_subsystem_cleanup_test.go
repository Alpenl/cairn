func TestObsoleteSubsystemCleanupMigratesLegacyObjects(t *testing.T) {
	dsn := isolatedMigrationDatabase(t)
	pool := migrationTargetPool(t, dsn)
	prepareProductionUpgradeFixture(t, pool)
	installLegacyLinkClassificationSchema(t, pool)

	if _, err := pool.Exec(t.Context(), `
		CREATE TABLE public.concept (id uuid PRIMARY KEY);
		CREATE TABLE public.concept_alias (
			alias text NOT NULL,concept_id uuid NOT NULL REFERENCES public.concept(id));
		CREATE TABLE public.concept_merge_proposal (id uuid PRIMARY KEY);
		CREATE TABLE public.link_concept (
			link_id uuid NOT NULL REFERENCES public.links(id),
			concept_id uuid NOT NULL REFERENCES public.concept(id));
		CREATE TABLE public.library_classification_rules (id uuid PRIMARY KEY);
		CREATE TABLE public.library_review_items (
			id uuid PRIMARY KEY,link_id uuid REFERENCES public.links(id));
		CREATE TABLE public.reader_content_history (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			link_id uuid NOT NULL REFERENCES public.links(id));
		CREATE TABLE public.feed_lifecycle_repair_audit (
			link_id uuid NOT NULL,
			classification text NOT NULL,
			PRIMARY KEY (link_id,classification));
		CREATE TABLE public.reader_tag_activity (
			tag text PRIMARY KEY,last_at timestamptz NOT NULL,last_link_id uuid);
		CREATE TABLE public.reader_domain_activity (
			domain text PRIMARY KEY,last_at timestamptz NOT NULL,last_link_id uuid);

		ALTER TABLE public.links
			ADD COLUMN embedding text,
			ADD COLUMN embedding_model text;
		ALTER TABLE public.sites
			ADD COLUMN needs_review boolean NOT NULL DEFAULT false,
			ADD COLUMN embedding text,
			ADD COLUMN embedding_model text;
		ALTER TABLE public.site_tags ADD COLUMN concept_id uuid;

		CREATE FUNCTION public.reader_capture_content_history() RETURNS trigger
		LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
		CREATE FUNCTION public.reader_cleanup_content_history(integer,integer) RETURNS integer
		LANGUAGE sql AS $$ SELECT 0 $$;
		CREATE FUNCTION public.bump_concept_global_revision_update() RETURNS trigger
		LANGUAGE plpgsql AS $$ BEGIN RETURN NULL; END $$;
		CREATE FUNCTION public.bump_link_concept_read_revision_update() RETURNS trigger
		LANGUAGE plpgsql AS $$ BEGIN RETURN NULL; END $$;
		CREATE TRIGGER trg_reader_capture_content_history
		BEFORE UPDATE OF content,content_document,content_revision ON public.links
		FOR EACH ROW EXECUTE FUNCTION public.reader_capture_content_history();

		DROP TRIGGER trg_sites_representation_write_gate_upd ON public.sites;
		CREATE TRIGGER trg_sites_representation_write_gate_upd
		BEFORE UPDATE OF first_collected_at,homepage_url,icon_url,id,intro,
			last_collected_at,name,needs_review,pinned,primary_entry_id,revision,site_key,updated_at
		ON public.sites FOR EACH STATEMENT
		EXECUTE FUNCTION public.guard_representation_write_gate();

		CREATE INDEX idx_link_translations_missing_reconcile
		ON public.link_translations (updated_at,id) INCLUDE (current_river_job_id)
		WHERE status IN ('pending','processing') AND current_river_job_id IS NOT NULL;
	`); err != nil {
		t.Fatalf("create legacy obsolete subsystem objects: %v", err)
	}
	assertObsoleteSubsystemSchemaState(t, pool, 10, 14, 4)
	assertIndexExists(t, pool, "idx_link_translations_missing_reconcile", true)
	assertIndexExists(t, pool, "idx_river_job_translation_terminal_history", true)
	feedLinkID := seedLegacyClassifiedLink(t, pool, "https://cleanup.example/feed", "Feed", "body", "summary")
	feedItemID := seedReaderFeedSaveItem(t, pool, "https://cleanup.example/feed", "cleanup-feed")
	if _, err := pool.Exec(t.Context(), `
		INSERT INTO reader_feed_saves (feed_item_id,link_id,created_link) VALUES ($1,$2,true)`, feedItemID, feedLinkID); err != nil {
		t.Fatalf("seed legacy Feed save state: %v", err)
	}
	if _, err := pool.Exec(t.Context(), `
		INSERT INTO reader_feed_feedback (item_key,action) VALUES ('link:'||$1::text,'hide'),('subscription:'||$2::text,'save')`, feedLinkID, feedItemID); err != nil {
		t.Fatalf("seed legacy Feed feedback state: %v", err)
	}

	translationIDs := seedObsoleteCleanupTranslations(t, pool)

	if err := migrate.Up(t.Context(), pool); err != nil {
		t.Fatalf("apply production schema upgrade: %v", err)
	}
	assertCurrentSchemaLedger(t, pool)
	assertObsoleteSubsystemSchemaState(t, pool, 0, 0, 0)
	assertIndexExists(t, pool, "idx_link_translations_missing_reconcile", false)
	assertIndexExists(t, pool, "idx_river_job_translation_terminal_history", false)
	assertObsoleteCleanupTranslationStates(t, pool, translationIDs)
	var hides, saveColumns, retiredTranslationColumns int
	if err := pool.QueryRow(t.Context(), `SELECT count(*) FROM reader_feed_hides`).Scan(&hides); err != nil {
		t.Fatalf("count migrated Feed hides: %v", err)
	}
	if err := pool.QueryRow(t.Context(), `SELECT count(*) FROM information_schema.columns
		WHERE table_schema='public' AND ((table_name='reader_feed_hides' AND column_name='action')
			OR (table_name='reader_feed_saves' AND column_name='created_link'))`).Scan(&saveColumns); err != nil {
		t.Fatalf("inspect simplified Feed columns: %v", err)
	}
	if hides != 1 || saveColumns != 0 {
		t.Fatalf("simplified Feed state = hides:%d obsolete_columns:%d, want 1/0", hides, saveColumns)
	}
	if err := pool.QueryRow(t.Context(), `SELECT count(*) FROM information_schema.columns
		WHERE table_schema='public' AND table_name='link_translations'
			AND column_name='current_river_job_id'`).Scan(&retiredTranslationColumns); err != nil {
		t.Fatalf("inspect retired translation columns: %v", err)
	}
	if retiredTranslationColumns != 0 {
		t.Fatalf("current_river_job_id columns = %d, want 0", retiredTranslationColumns)
	}
}

