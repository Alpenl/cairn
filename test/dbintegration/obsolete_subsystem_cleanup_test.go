func assertObsoleteCleanupTranslationStates(t *testing.T, pool migrationRowQuerier, ids obsoleteCleanupTranslationIDs) {
	t.Helper()
	var settled, active, unbound int
	if err := pool.QueryRow(t.Context(), `SELECT
		count(*) FILTER (WHERE id IN ($1,$2,$5,$6) AND status='failed'
			AND error_msg='翻译服务暂时不可用，请重试'),
		count(*) FILTER (WHERE id=$3 AND status='pending' AND error_msg IS NULL),
		count(*) FILTER (WHERE id=$4 AND status='pending' AND error_msg IS NULL)
	FROM public.link_translations
	WHERE id IN ($1,$2,$3,$4,$5,$6)`,
		ids.terminal, ids.missing, ids.active, ids.unbound, ids.legacyBound, ids.legacyUnbound).
		Scan(&settled, &active, &unbound); err != nil {
		t.Fatalf("inspect obsolete cleanup translation states: %v", err)
	}
	if settled != 4 || active != 1 || unbound != 1 {
		t.Fatalf("translation cleanup states = settled:%d active:%d unbound:%d, want 4/1/1",
			settled, active, unbound)
	}
	var legacyState string
	var legacyFinalized bool
	if err := pool.QueryRow(t.Context(), `SELECT state::text,finalized_at IS NOT NULL
		FROM public.river_job WHERE id=$1`, ids.legacyRiverJobID).Scan(&legacyState, &legacyFinalized); err != nil {
		t.Fatalf("inspect legacy translation River job: %v", err)
	}
	if legacyState != "cancelled" || !legacyFinalized {
		t.Fatalf("legacy translation River job = %s/finalized:%v, want cancelled/true",
			legacyState, legacyFinalized)
	}
}

func assertObsoleteSubsystemSchemaState(
	t *testing.T,
	pool migrationRowQuerier,
	wantTables int,
	wantColumns int,
	wantFunctions int,
) {
	t.Helper()

	var tables, columns, functions int
	if err := pool.QueryRow(t.Context(), `
		SELECT
			(SELECT count(*) FROM information_schema.tables
			 WHERE table_schema='public' AND table_name IN (
				'concept','concept_alias','concept_merge_proposal','link_concept',
				'library_classification_rules','library_review_items','reader_content_history',
				'reader_todo_projection_backfills','feed_lifecycle_repair_audit',
				'reader_tag_activity','reader_domain_activity')),
			(SELECT count(*) FROM information_schema.columns
			 WHERE table_schema='public' AND (
				(table_name='links' AND column_name IN (
					'embedding','embedding_model','library_kind_source','predicted_library_kind',
					'classification_confidence','classification_reason','classification_explanation',
					'classifier_version','requested_library_kind','requested_library_kind_source')) OR
				(table_name='sites' AND column_name IN ('needs_review','embedding','embedding_model')) OR
				(table_name='site_tags' AND column_name='concept_id'))),
			(SELECT count(*) FROM pg_proc AS proc
			 JOIN pg_namespace AS ns ON ns.oid=proc.pronamespace
			 WHERE ns.nspname='public' AND proc.proname IN (
				'reader_capture_content_history','reader_cleanup_content_history',
				'bump_concept_global_revision_update','bump_link_concept_read_revision_update'))
	`).Scan(&tables, &columns, &functions); err != nil {
		t.Fatalf("inspect obsolete subsystem schema: %v", err)
	}
	if tables != wantTables || columns != wantColumns || functions != wantFunctions {
		t.Fatalf("obsolete subsystem schema = tables:%d columns:%d functions:%d, want %d/%d/%d",
			tables, columns, functions, wantTables, wantColumns, wantFunctions)
	}
}
